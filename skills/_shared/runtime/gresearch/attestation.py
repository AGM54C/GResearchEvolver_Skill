"""Ed25519 receipts from the trusted evaluator, with caller-pinned context and replay checks."""
from __future__ import annotations
import base64
import os
import re
from pathlib import Path
import time
import uuid
from .core import ResearchError, canonical, fingerprint, write_json


def keygen(destination):
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
    from cryptography.hazmat.primitives import serialization
    root = Path(destination)
    root.mkdir(parents=True, exist_ok=False)
    key = Ed25519PrivateKey.generate()
    raw = key.private_bytes(serialization.Encoding.Raw, serialization.PrivateFormat.Raw, serialization.NoEncryption())
    path = root / 'signing.key'
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, 'wb') as f: f.write(raw)
    public = base64.b64encode(key.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)).decode()
    write_json(root / 'public.json', {'algorithm': 'Ed25519', 'public_key': public})
    return {'private_key_path': str(path), 'public_key': public,
            'deployment': 'Keep private key on the evaluator host, outside every candidate mount. Restrict Windows ACLs on that host.'}


def signer(config):
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
    from cryptography.hazmat.primitives import serialization
    path = os.getenv(config.get('key_path_env', 'GRESEARCH_SIGNING_KEY'))
    if not path: raise ResearchError('Trusted evaluator signing-key path environment variable is unset')
    key = Ed25519PrivateKey.from_private_bytes(Path(path).read_bytes())
    public = base64.b64encode(key.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)).decode()
    if public != config.get('public_key'): raise ResearchError('Evaluator signing key does not match pinned public key')
    return key


def sign(config, payload):
    if {'version','nonce','issued_at'} & set(payload):raise ResearchError('Receipt metadata is generated by the signer, not supplied in payload')
    body = {'version': 1, 'nonce': uuid.uuid4().hex, 'issued_at': time.time(), **payload}
    signature = signer(config).sign(canonical(body).encode('utf-8'))
    return {'payload': body, 'signature': base64.b64encode(signature).decode(), 'algorithm': 'Ed25519'}


def verified_payload(envelope, public_key, expected):
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey
    from cryptography.exceptions import InvalidSignature
    # Callers must pin context from their own release request, not copy it from receipt.
    required = {'epoch', 'protocol_hash', 'evaluator_hash', 'candidate_hash', 'trial'}
    if not required.issubset(expected): raise ResearchError('Pin epoch, protocol, evaluator, candidate and trial')
    if any(not isinstance(expected[k],str) or not expected[k].strip() for k in required):
        raise ResearchError('Receipt context pins must be nonempty strings')
    if any(not re.fullmatch('[0-9a-f]{64}',expected[k]) for k in ('protocol_hash','evaluator_hash','candidate_hash')):
        raise ResearchError('Pin actual SHA-256 hashes for protocol, evaluator and candidate')
    if envelope.get('algorithm')!='Ed25519':raise ResearchError('Unsupported receipt algorithm')
    body = envelope.get('payload', {})
    try:
        Ed25519PublicKey.from_public_bytes(base64.b64decode(public_key, validate=True)).verify(
            base64.b64decode(envelope['signature'], validate=True), canonical(body).encode('utf-8'))
    except (InvalidSignature, ValueError, KeyError) as exc:
        raise ResearchError('Invalid evaluator signature') from exc
    if any(body.get(k) != v for k, v in expected.items()): raise ResearchError('Receipt context mismatch')
    if body.get('isolation') != 'docker' or not isinstance(body.get('nonce'),str) or not re.fullmatch('[0-9a-f]{32}',body['nonce']) or body.get('version')!=1:
        raise ResearchError('Missing or invalid isolation/nonce/version')
    return body


def verify(envelope, public_key, expected):
    body = verified_payload(envelope, public_key, expected)
    if body.get('split') != 'audit' or body.get('passed') is not True or body.get('promoted') is not True:
        raise ResearchError('Receipt does not authorize an audit promotion')
    return body


def verify_evaluation(envelope, public_key, expected):
    """A passed comparison is not yet authorization to deploy the candidate."""
    body = verified_payload(envelope, public_key, expected)
    if body.get('split') != 'audit' or body.get('passed') is not True or body.get('promoted') is not False:
        raise ResearchError('Receipt is not a passed, unpromoted audit')
    return body


def accept(store, envelope, public_key, expected):
    body = verify(envelope, public_key, expected)
    key = 'accepted-receipt:' + body['nonce']
    with store.tx():
        if store.get_value(key): raise ResearchError('Receipt replay rejected')
        store.set_value(key, {'receipt_hash': fingerprint(envelope), 'accepted_at': time.time()})
        store.event('attestation', 'promotion_receipt_accepted', body)
    return {'accepted': True, 'candidate_hash': body['candidate_hash'], 'nonce': body['nonce']}
